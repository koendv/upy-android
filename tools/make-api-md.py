#!/usr/bin/env python3
# Writes doc/API.md from the help() text of every module, read from the phone
# through adb exec. ANDROID_SERIAL picks the device.
#   tools/make-api-md.py
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _upy_adb_core as core

MODULES = ["camera", "display", "android", "location", "imu", "image", "gif", "mjpeg", "crc", "ulab", "tflite", "litert", "umqtt", "http", "zipfile"]
MARK = "@@@@"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "doc", "API.md")

SCRIPT = """
import %s
for name in %r:
    print(%r + name)
    print(eval(name + '.help()'))
""" % (", ".join(MODULES), MODULES, MARK)

HEADER = """# API reference

Generated by `tools/make-api-md.py` from the `help()` text of each module. Do not edit by hand.

Modules: %s.
"""


def main():
    output, error = core.run_script(SCRIPT)
    if error is not None:
        sys.exit("make-api-md: " + error)
    if core.last_status != "ok":
        sys.exit("make-api-md: status %r, exception %r\n%s" % (core.last_status, core.last_exception, output))
    sections = output.split(MARK)[1:]
    names = [s.split("\n", 1)[0] for s in sections]
    if names != MODULES:
        sys.exit("make-api-md: got modules %r, expected %r" % (names, MODULES))
    quote = lambda names: ", ".join("`%s`" % n for n in names)
    parts = [HEADER % quote(MODULES)]
    for section in sections:
        name, text = section.split("\n", 1)
        parts.append("## %s\n\n```\n%s\n```\n" % (name, text.strip("\n")))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print("wrote", OUT)


main()
